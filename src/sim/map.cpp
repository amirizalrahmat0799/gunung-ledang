Map Map::parse(std::string_view text) {
    Map m;
    std::vector<std::string_view> rows;
    size_t start = 0;
    while (start <= text.size()) {
        size_t end = text.find('\n', start);
        if (end == std::string_view::npos) end = text.size();
        std::string_view row = text.substr(start, end - start);
        if (!row.empty() && row.back() == '\r') row.remove_suffix(1);
        if (!row.empty()) rows.push_back(row);
        start = end + 1;
    }
    if (rows.empty()) throw std::runtime_error("empty map");
    m.width_ = static_cast<int>(rows[0].size());
    m.height_ = static_cast<int>(rows.size());
    m.tiles_.assign(static_cast<size_t>(m.width_ * m.height_), Tile::Empty);
    for (int y = 0; y < m.height_; ++y) {
        if (static_cast<int>(rows[static_cast<size_t>(y)].size()) != m.width_) {
            throw std::runtime_error("map row " + std::to_string(y) + " has the wrong length");
        }
        for (int x = 0; x < m.width_; ++x) {
            const char c = rows[static_cast<size_t>(y)][static_cast<size_t>(x)];
            Tile t = Tile::Empty;
            switch (c) {
                case '#': t = Tile::Solid; break;
                case '=': t = Tile::Platform; break;
                case '^': t = Tile::Spikes; break;
                case '.': break;
                case 'P': m.markers_.push_back({MarkerKind::PlayerSpawn, x, y}); break;
                case 'L': m.markers_.push_back({MarkerKind::Lantern, x, y}); break;
                case 'h': m.markers_.push_back({MarkerKind::Penanggal, x, y}); break;
                case 'p': m.markers_.push_back({MarkerKind::Pocong, x, y}); break;
                case 'D': m.markers_.push_back({MarkerKind::ShrineDash, x, y}); break;
                case 'J': m.markers_.push_back({MarkerKind::ShrineDoubleJump, x, y}); break;
                case 'W': m.markers_.push_back({MarkerKind::ShrineWallJump, x, y}); break;
                case 'B': m.markers_.push_back({MarkerKind::Guardian, x, y}); break;
                case 'G': m.markers_.push_back({MarkerKind::Goal, x, y}); break;
                default:
                    throw std::runtime_error(std::string("unknown map character '") + c + "'");
            }
            m.tiles_[static_cast<size_t>(y * m.width_ + x)] = t;
        }
    }
    return m;
}

const Map& Map::world() {
    static const Map map = parse(kWorld);
    return map;
}

